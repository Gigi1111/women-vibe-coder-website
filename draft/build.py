"""Rebuild the draft review copy of the site.

    python3 draft/build.py

Copies ../index.html to draft/index.html, points its local links one folder up,
hides the draft from search engines, and adds the comment layer
(comments.css, firebase-config.js, comments.js). Edit index.html, never
draft/index.html, then rerun this script.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "index.html"
TARGET = ROOT / "draft" / "index.html"

html = SOURCE.read_text(encoding="utf-8")

# Local links (assets/…, starter-kit/) live one folder up from /draft/.
html = re.sub(
    r'(\b(?:src|href)=")(?!https?:|#|mailto:|tel:|data:|/|\.\./)([^"]+)"',
    r'\1../\2"',
    html,
)

html = html.replace("<title>", "<title>Draft · ", 1)
html = html.replace(
    '<meta charset="UTF-8">',
    '<meta charset="UTF-8">\n  <meta name="robots" content="noindex, nofollow">',
    1,
)

comment_layer = (
    '  <!-- Draft review comments (see draft/README.md) -->\n'
    '  <link rel="stylesheet" href="comments.css">\n'
    '  <script src="firebase-config.js"></script>\n'
    '  <script src="comments.js" defer></script>\n'
)
if "</body>" not in html:
    raise SystemExit("index.html has no </body> tag; cannot add the comment layer.")
html = html.replace("</body>", comment_layer + "</body>", 1)

# Note sits after the doctype so the page stays in standards mode.
first_line, rest = html.split("\n", 1)
html = (
    first_line
    + "\n<!-- GENERATED by draft/build.py from ../index.html. Edit index.html, then rerun the script. -->\n"
    + rest
)

TARGET.write_text(html, encoding="utf-8")
print(f"Wrote {TARGET.relative_to(ROOT)}")
